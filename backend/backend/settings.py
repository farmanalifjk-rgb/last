def _non_negative_number_env(name, default, *, integer=False):
    raw = os.environ.get(name, "").strip() or str(default)
    try:
        value = int(raw) if integer else float(raw)
    except ValueError:
        raise RuntimeError(f"{name} must be a {'whole ' if integer else ''}number (got {raw!r}).") from None
    if value < 0:
        raise RuntimeError(f"{name} must not be negative.")
    return value


